CREATE TABLE vehicles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plate VARCHAR(32) NOT NULL UNIQUE,
  make VARCHAR(80) NOT NULL,
  model VARCHAR(80) NOT NULL,
  model_year INTEGER NOT NULL,
  odometer_miles BIGINT NOT NULL DEFAULT 0,
  status VARCHAR(24) NOT NULL DEFAULT 'AVAILABLE'
);
CREATE TABLE drivers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  phone VARCHAR(32),
  active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE trips (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
  driver_id BIGINT NOT NULL REFERENCES drivers(id),
  origin VARCHAR(160) NOT NULL,
  destination VARCHAR(160) NOT NULL,
  pickup_at TIMESTAMP WITH TIME ZONE NOT NULL,
  delivery_at TIMESTAMP WITH TIME ZONE NOT NULL,
  freight_rate DECIMAL(12,2) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'PLANNED',
  CONSTRAINT valid_trip_dates CHECK (delivery_at > pickup_at)
);
CREATE INDEX idx_trip_vehicle_times ON trips (vehicle_id, pickup_at, delivery_at);
CREATE INDEX idx_trip_driver_times ON trips (driver_id, pickup_at, delivery_at);
